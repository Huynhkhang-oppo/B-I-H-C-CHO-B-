// Plugin to duplicate index.html to 404.html for GitHub Pages SPA routing
function githubPagesSpaPlugin(): Plugin {
  return {
    name: 'github-pages-spa',
    closeBundle() {
      try {
        const distDir = path.resolve(process.cwd(), 'dist');
        const indexPath = path.join(distDir, 'index.html');
        const notFoundPath = path.join(distDir, '404.html');
        if (fs.existsSync(indexPath)) {
          fs.copyFileSync(indexPath, notFoundPath);
          console.log('[GitHub Pages] Đã tạo dist/404.html để chống màn hình trắng khi tải lại trang!');
        }
      } catch (err) {
        console.warn('Could not copy 404.html:', err);
      }
    },
  };
}

